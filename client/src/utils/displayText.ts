const TRADITIONAL_TO_SIMPLIFIED = Object.fromEntries(TRADITIONAL_PAIRS)
const textCache = new Map<string, string>()
const htmlCache = new Map<string, string>()

function simplifyChinese(value: string): string {
  return Array.from(value).map(char => TRADITIONAL_TO_SIMPLIFIED[char] || char).join('')
}

export function cleanDisplayText(value: string | null | undefined): string {
  return String(value ?? '')
    .replace(/\|br\s*>?/gi, '\n')
    .replace(/&lt;br\s*\/?&gt;/gi, '\n')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/?(?:b|strong|i|em)>/gi, '')
}

export function localizeDisplayText(value: string | null | undefined, language: DisplayLanguage = 'zh-Hant'): string {
  const cleaned = cleanDisplayText(value)
  const key = language + ':' + cleaned
  const cached = textCache.get(key)
  if (cached !== undefined) return cached
  const result = language === 'zh-Hans' ? simplifyChinese(cleaned) : cleaned
  textCache.set(key, result)
  return result
}

export function cleanDisplayHtml(value: string | null | undefined): string {
  return String(value ?? '')
    .replace(/\|br\s*>?/gi, '<br>')
    .replace(/&lt;br\s*\/?&gt;/gi, '<br>')
}

export function localizeDisplayHtml(value: string | null | undefined, language: DisplayLanguage = 'zh-Hant'): string {
  const cleaned = cleanDisplayHtml(value)
  const key = language + ':' + cleaned
  const cached = htmlCache.get(key)
  if (cached !== undefined) return cached
  const result = language === 'zh-Hans' ? simplifyChinese(cleaned) : cleaned
  htmlCache.set(key, result)
  return result
}

/** 方括号符号 → 中文（[skull]→骷髅，[cultist]→邪教徒 等） */
